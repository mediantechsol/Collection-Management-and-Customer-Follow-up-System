-- ============================================================================
-- الجدولة اليومية لتوليد التنبيهات
--
-- في النموذج الأولي كان التوليد يتم بزر يدوي فقط، أي أن التنبيهات لا تظهر
-- لأي موظف حتى يفتح المدير الشاشة ويضغط الزر. هنا تُجدول يومياً، ويبقى الزر
-- متاحاً للمدير كتشغيل فوري.
--
-- ⚠️ pg_cron متاح على Supabase (Database → Extensions). إن لم يكن مفعّلاً
-- سيفشل هذا الملف — فعّله من لوحة التحكم ثم أعد التشغيل، أو احذف هذا الملف
-- واعتمد على الزر اليدوي.
-- التوقيت أدناه 03:00 UTC = 06:00 صباحاً بتوقيت اليمن (UTC+3)؛
-- عدّله حسب ما يناسب بداية دوام المكتب.
-- ============================================================================

create extension if not exists pg_cron with schema extensions;

select cron.schedule(
  'generate-daily-notifications',
  '0 3 * * *',                                  -- 03:00 UTC = 06:00 صباحاً بتوقيت اليمن
  $$ select public.generate_daily_notifications(); $$
);

